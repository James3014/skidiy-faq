/**
 * Analytics API Routes
 *
 * Endpoints:
 * - GET /api/v1/analytics/llm-stats - Get LLM usage statistics
 * - GET /api/v1/analytics/provider-comparison - Compare provider performance
 * - GET /api/v1/analytics/popular-queries - Get popular queries
 * - GET /api/v1/analytics/cost-report - Get cost breakdown
 * - GET /api/v1/analytics/faq-insights - Get aggregated FAQ insights for SKIDIY platform
 */

const express = require('express');
const router = express.Router();
const AnalyticsService = require('../services/analytics-service');
const AlertService = require('../services/alert-service');
const { AppError } = require('../middleware/error-handler');
const { sendSuccess } = require('../utils/response-formatter');
const requireApiKey = require('../middleware/api-key');
const path = require('path');
const fs = require('fs').promises;

// Initialize Analytics Service
let analyticsService = null;
let alertService = null;

try {
  analyticsService = new AnalyticsService();
  console.log('[Analytics API] Analytics Service initialized');

  // Initialize Alert Service
  alertService = new AlertService(analyticsService, {
    dailyCostLimit: parseFloat(process.env.DAILY_COST_LIMIT) || 10.0,
    monthlyCostLimit: parseFloat(process.env.MONTHLY_COST_LIMIT) || 300.0,
    hourlyRequestLimit: parseInt(process.env.HOURLY_REQUEST_LIMIT) || 100,
    errorRateThreshold: parseFloat(process.env.ERROR_RATE_THRESHOLD) || 10,
    alertCooldown: parseInt(process.env.ALERT_COOLDOWN) || 60,
    enabled: process.env.ALERTS_ENABLED !== 'false'
  });

  // Add console alert handler
  alertService.addHandler((alert) => {
    console.log(`[Alert] ${alert.severity.toUpperCase()}: ${alert.message}`);
  });

  console.log('[Analytics API] Alert Service initialized');
} catch (error) {
  console.error('[Analytics API] Failed to initialize:', error.message);
}

/**
 * GET /api/v1/analytics/llm-stats
 *
 * Get comprehensive LLM usage statistics
 *
 * Query params:
 * - start_date: ISO date string (optional)
 * - end_date: ISO date string (optional)
 * - provider: Provider name filter (optional)
 * - limit: Number of recent queries to return (default: 100)
 *
 * Response:
 * {
 *   "success": true,
 *   "data": {
 *     "overall": {
 *       "totalRequests": 150,
 *       "successfulRequests": 145,
 *       "failedRequests": 5,
 *       "successRate": "96.67",
 *       "totalTokens": 123456,
 *       "totalCost": "1.2345",
 *       "avgResponseTime": 850,
 *       "avgFaqItems": "3.2"
 *     },
 *     "byProvider": [...],
 *     "recent": [...],
 *     "daily": [...]
 *   }
 * }
 */
router.get('/llm-stats', async (req, res, next) => {
  try {
    if (!analyticsService) {
      throw new AppError('SERVICE_UNAVAILABLE', 'Analytics 服務尚未初始化', 503);
    }

    const {
      start_date: startDate,
      end_date: endDate,
      provider,
      limit = 100
    } = req.query;

    const stats = analyticsService.getLLMStats({
      startDate,
      endDate,
      provider,
      limit: parseInt(limit, 10)
    });

    sendSuccess(res, stats, 200, {
      timestamp: new Date().toISOString()
    });
  } catch (error) {
    next(error);
  }
});

