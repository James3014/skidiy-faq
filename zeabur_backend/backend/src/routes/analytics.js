/**
 * GET /api/v1/analytics/cost-report
 *
 * Get detailed cost breakdown by provider and model
 *
 * Query params:
 * - start_date: ISO date string (optional)
 * - end_date: ISO date string (optional)
 *
 * Response:
 * {
 *   "success": true,
 *   "data": {
 *     "totalCost": "2.5678",
 *     "byProvider": {
 *       "gemini": {
 *         "cost": "0.1250",
 *         "requests": 100,
 *         "avgCostPerRequest": "0.001250"
 *       },
 *       "claude": {...}
 *     },
 *     "projectedMonthlyCost": "75.00"
 *   }
 * }
 */
router.get('/cost-report', async (req, res, next) => {
  try {
    if (!analyticsService) {
      throw new AppError('SERVICE_UNAVAILABLE', 'Analytics 服務尚未初始化', 503);
    }

    const {
      start_date: startDate,
      end_date: endDate
    } = req.query;

    // Get stats for cost calculation
    const stats = analyticsService.getLLMStats({ startDate, endDate });

    // Calculate cost breakdown
    const byProvider = {};
    for (const provider of stats.byProvider) {
      byProvider[provider.provider] = {
        cost: (provider.cost || 0).toFixed(4),
        requests: provider.requests,
        avgCostPerRequest: provider.requests > 0
          ? ((provider.cost || 0) / provider.requests).toFixed(6)
          : '0.000000'
      };
    }

    // Project monthly cost (assuming current rate)
    const daysOfData = stats.daily.length || 1;
    const avgDailyCost = parseFloat(stats.overall.totalCost) / daysOfData;
    const projectedMonthlyCost = (avgDailyCost * 30).toFixed(2);

    const costReport = {
      totalCost: stats.overall.totalCost,
      byProvider,
      projectedMonthlyCost,
      dataPoints: {
        startDate: startDate || stats.daily[stats.daily.length - 1]?.date,
        endDate: endDate || stats.daily[0]?.date,
        totalDays: daysOfData
      }
    };

    sendSuccess(res, costReport, 200, {
      timestamp: new Date().toISOString()
    });
  } catch (error) {
    next(error);
  }
});

/**
 * GET /api/v1/analytics/export
 *
 * Export analytics data as CSV
 *
 * Query params:
 * - type: Export type (llm_usage | provider_stats)
 * - start_date: ISO date string (optional)
 * - end_date: ISO date string (optional)
 *
 * Response: CSV file download
 */
router.get('/export', async (req, res, next) => {
  try {
    if (!analyticsService) {
      throw new AppError('SERVICE_UNAVAILABLE', 'Analytics 服務尚未初始化', 503);
    }

    const {
      type = 'llm_usage',
      start_date: startDate,
      end_date: endDate
    } = req.query;

    // Get data
    const stats = analyticsService.getLLMStats({ startDate, endDate, limit: 10000 });

    let csv = '';
    let filename = '';

    if (type === 'llm_usage') {
      // Generate CSV for LLM usage
      csv = 'Timestamp,Query,Provider,Model,Tokens,Cost,Response Time,Success\n';
      for (const row of stats.recent) {
        csv += `"${row.timestamp}","${row.query_text.replace(/"/g, '""')}",${row.provider},${row.model},${row.total_tokens},${row.cost_usd || 0},${row.response_time_ms},${row.success}\n`;
      }
      filename = `llm-usage-${new Date().toISOString().split('T')[0]}.csv`;
    } else if (type === 'provider_stats') {
      // Generate CSV for provider comparison
      csv = 'Provider,Requests,Success Rate,Total Tokens,Total Cost,Avg Response Time,Cost Per Request\n';
      const comparison = analyticsService.getProviderComparison();
      for (const row of comparison) {
        csv += `${row.provider},${row.totalRequests},${row.successRate}%,${row.totalTokens},${row.totalCost},${row.avgResponseTime}ms,${row.costPerRequest}\n`;
      }
      filename = `provider-stats-${new Date().toISOString().split('T')[0]}.csv`;
    }

    res.setHeader('Content-Type', 'text/csv');
    res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
    res.send(csv);
  } catch (error) {
    next(error);
  }
});

