/**
 * GET /api/v1/analytics/hot-faqs
 *
 * Get most clicked/viewed FAQs (hot/trending FAQs)
 *
 * Query params:
 * - limit: Number of FAQs to return (default: 5)
 * - days: Number of days to look back (default: 7)
 *
 * Response:
 * {
 *   "success": true,
 *   "data": {
 *     "hot_faqs": [
 *       {
 *         "faq_id": "faq.booking.001",
 *         "clicks": 120,
 *         "unique_sessions": 45,
 *         "last_clicked_at": "2025-11-01T08:00:00.000Z"
 *       }
 *     ]
 *   }
 * }
 */
router.get('/hot-faqs', async (req, res, next) => {
  try {
    if (!analyticsService) {
      throw new AppError('SERVICE_UNAVAILABLE', 'Analytics 服務尚未初始化', 503);
    }

    const limit = parseInt(req.query.limit) || 5;
    const days = parseInt(req.query.days) || 7;
    const languageFilter = req.query.language || null;

    const db = analyticsService.db;
    const cutoffDate = new Date();
    cutoffDate.setDate(cutoffDate.getDate() - days);
    const cutoffIso = cutoffDate.toISOString();

    const params = [cutoffIso];
    if (languageFilter) params.push(languageFilter);
    params.push(limit);

    const hotFAQs = db.prepare(`
      SELECT
        faq_id,
        COUNT(*) as clicks,
        COUNT(DISTINCT COALESCE(session_id, view_id, faq_id || '_' || strftime('%s', timestamp))) as unique_sessions,
        MAX(timestamp) as last_clicked_at
      FROM faq_views
      WHERE timestamp >= ?
      ${languageFilter ? 'AND language = ?' : ''}
      GROUP BY faq_id
      ORDER BY clicks DESC, last_clicked_at DESC
      LIMIT ?
    `).all(...params);

    const langStats = db.prepare(`
      SELECT language, COUNT(*) as clicks
      FROM faq_views
      WHERE timestamp >= ?
      GROUP BY language
      ORDER BY clicks DESC
    `).all(cutoffIso);

    const sourceStats = db.prepare(`
      SELECT COALESCE(source, 'unknown') as source, COUNT(*) as clicks
      FROM faq_views
      WHERE timestamp >= ?
      GROUP BY COALESCE(source, 'unknown')
      ORDER BY clicks DESC
    `).all(cutoffIso);

    sendSuccess(res, {
      hot_faqs: hotFAQs,
      period_days: days,
      total_faqs: hotFAQs.length,
      language: languageFilter || 'all',
      by_language: langStats,
      by_source: sourceStats
    }, 200, {
      timestamp: new Date().toISOString()
    });
  } catch (error) {
    next(error);
  }
});

/**
 * POST /api/v1/analytics/track-faq-view
 *
 * Track FAQ view/click event
 *
 * Body:
 * {
 *   "faq_id": "faq.booking.001",
 *   "clicked": true,
 *   "language": "zh",
 *   "source": "search_results",
 *   "query_text": "如何預約教練",
 *   "position": 1,
 *   "time_to_click_ms": 1500
 * }
 *
 * Response:
 * {
 *   "success": true,
 *   "data": { "tracked": true, "source": "search_results", "language": "zh" }
 * }
 */
router.post('/track-faq-view', async (req, res, next) => {
  try {
    if (!analyticsService) {
      throw new AppError('SERVICE_UNAVAILABLE', 'Analytics 服務尚未初始化', 503);
    }

    const {
      faq_id,
      clicked = true,
      query_id,
      query_text,
      position,
      source = 'search_results',
      time_to_click_ms,
      language = 'zh',
      session_id,
      view_id = null,
      user_id = null
    } = req.body;

    if (!faq_id) {
      throw new AppError('VALIDATION_ERROR', 'faq_id 為必填欄位', 400);
    }

    const normalizedLanguage = typeof language === 'string' && language.trim().length > 0
      ? language.trim()
      : 'zh';
    const normalizedSource = typeof source === 'string' && source.trim().length > 0
      ? source.trim()
      : 'search_results';
    const positionValue = Number.isFinite(position) ? position : parseInt(position || '0', 10);

    const db = analyticsService.db;
    const stmt = db.prepare(`
      INSERT INTO faq_views (view_id, faq_id, query_id, query_text, position, source, clicked, time_to_click_ms, language, session_id, user_id)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `);

    stmt.run(
      view_id || null,
      faq_id,
      query_id || null,
      query_text || null,
      Number.isNaN(positionValue) ? 0 : positionValue,
      normalizedSource,
      clicked ? 1 : 0,
      time_to_click_ms || null,
      normalizedLanguage,
      session_id || null,
      user_id || null
    );

    sendSuccess(res, {
      tracked: true,
      faq_id,
      view_id: view_id || null,
      source: normalizedSource,
      language: normalizedLanguage
    }, 201, {
      timestamp: new Date().toISOString()
    });
  } catch (error) {
    next(error);
  }
});

