/**
 * GET /api/v1/analytics/faq-insights
 *
 * Returns aggregated FAQ insights for the SKIDIY platform.
 * Data is generated by the analytics worker and stored as JSON.
 */
router.get('/faq-insights', requireApiKey(), async (req, res, next) => {
  try {
    const summaryPath =
      process.env.FAQ_INSIGHTS_PATH ||
      path.join(__dirname, '../../../data/analytics_summary.json');

    let payloadRaw;
    try {
      payloadRaw = await fs.readFile(summaryPath, 'utf-8');
    } catch (readError) {
      throw new AppError(
        'FAQ_INSIGHTS_NOT_READY',
        'FAQ insights summary file is not available. Ensure analytics worker has generated the file.',
        503,
        { summaryPath }
      );
    }

    let payload;
    try {
      payload = JSON.parse(payloadRaw);
    } catch (parseError) {
      throw new AppError(
        'FAQ_INSIGHTS_INVALID',
        'FAQ insights summary file contains invalid JSON.',
        500,
        { summaryPath }
      );
    }

    if (!payload || typeof payload !== 'object') {
      throw new AppError(
        'FAQ_INSIGHTS_INVALID',
        'FAQ insights payload is missing or malformed.',
        500,
        { summaryPath }
      );
    }

    const {
      topViewedResorts = [],
      topInteractedFaqs = [],
      generated_at: generatedAt = null
    } = payload;

    sendSuccess(
      res,
      {
        topViewedResorts,
        topInteractedFaqs,
        generated_at: generatedAt
      },
      200,
      {
        timestamp: new Date().toISOString(),
        source: 'analytics-summary'
      }
    );
  } catch (error) {
    next(error);
  }
});

