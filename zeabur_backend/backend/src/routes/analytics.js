/**
 * PUT /api/v1/analytics/alerts/config
 *
 * Update alert configuration
 *
 * Request body:
 * {
 *   "dailyCostLimit": 15.0,
 *   "monthlyCostLimit": 400.0,
 *   "hourlyRequestLimit": 150,
 *   "errorRateThreshold": 15,
 *   "alertCooldown": 30,
 *   "enabled": true
 * }
 *
 * Response:
 * {
 *   "success": true,
 *   "data": {
 *     "config": {...}
 *   }
 * }
 */
router.put('/alerts/config', async (req, res, next) => {
  try {
    if (!alertService) {
      throw new AppError('SERVICE_UNAVAILABLE', '警報服務尚未初始化', 503);
    }

    const {
      dailyCostLimit,
      monthlyCostLimit,
      hourlyRequestLimit,
      errorRateThreshold,
      alertCooldown,
      enabled
    } = req.body;

    const newConfig = {};

    if (dailyCostLimit !== undefined) newConfig.dailyCostLimit = parseFloat(dailyCostLimit);
    if (monthlyCostLimit !== undefined) newConfig.monthlyCostLimit = parseFloat(monthlyCostLimit);
    if (hourlyRequestLimit !== undefined) newConfig.hourlyRequestLimit = parseInt(hourlyRequestLimit);
    if (errorRateThreshold !== undefined) newConfig.errorRateThreshold = parseFloat(errorRateThreshold);
    if (alertCooldown !== undefined) newConfig.alertCooldown = parseInt(alertCooldown);
    if (enabled !== undefined) newConfig.enabled = Boolean(enabled);

    alertService.updateConfig(newConfig);

    sendSuccess(res, {
      config: alertService.config
    }, 200, {
      timestamp: new Date().toISOString()
    });
  } catch (error) {
    next(error);
  }
});

